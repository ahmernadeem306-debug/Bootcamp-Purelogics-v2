import h2o
from h2o.automl import H2OAutoML
import pandas as pd
from sklearn.datasets import load_wine

# 1. Load a tabular dataset from sklearn
# We are using the Wine recognition dataset (Multiclass Classification)
raw_data = load_wine(as_frame=True)
df = raw_data.frame

# 2. Define the task type and target column
# Target: 'target' (Classifies wine into 3 categories)
# Task: Classification
target_col = "target"
feature_cols = raw_data.feature_names

# 3. Initialize H2O and convert to H2OFrame
h2o.init()

# Convert pandas DataFrame to H2OFrame
hf = h2o.H2OFrame(df)

# IMPORTANT: Target must be a factor (categorical) for a classification task
hf[target_col] = hf[target_col].asfactor()

# 4. Split into train (80%) and test (20%) ratios
train_hf, test_hf = hf.split_frame(ratios=[0.8], seed=42)

# 5. Run H2OAutoML with specified constraints
aml = H2OAutoML(
    max_runtime_secs=300,
    max_models=15,
    nfolds=5,
    balance_classes=True,  # True because this is a classification task
    seed=42,
)

# Train the models
aml.train(x=feature_cols, y=target_col, training_frame=train_hf)

# 6. Display leaderboard and evaluate on the test set
print("\n--- AutoML Leaderboard ---")
leaderboard = aml.leaderboard
print(leaderboard.head(rows=leaderboard.nrows))

# Evaluate the best model on the test set
print("\n--- Test Set Evaluation ---")
best_model = aml.leader
performance = best_model.model_performance(test_data=test_hf)
print(performance)

# 7. Save leaderboard to a pandas DataFrame and export to CSV
leaderboard_df = leaderboard.as_data_frame()
leaderboard_df.to_csv("leaderboard.csv", index=False)

print("\n[SUCCESS] Leaderboard successfully exported to 'leaderboard.csv'")

