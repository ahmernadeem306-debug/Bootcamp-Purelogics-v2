"""## 3. Regression Example: California Housing"""

import pandas as pd
import numpy as np
from sklearn.datasets import fetch_california_housing
from sklearn.model_selection import train_test_split
import h2o
from h2o.automl import H2OAutoML
from sklearn.metrics import mean_squared_error, r2_score

# Initialize H2O
h2o.init(max_mem_size="2G", nthreads=-1)

import pandas as pd

# Load data from local CSV files
train_df = pd.read_csv('/content/sample_data/california_housing_train.csv')
test_df = pd.read_csv('/content/sample_data/california_housing_test.csv')

# Combine train and test data
data_df = pd.concat([train_df, test_df], ignore_index=True)

# Separate features (X) and target (y)
X = data_df.drop(columns=['median_house_value'])
y = data_df['median_house_value'].rename('target')

# Display the first few rows of X and y to confirm
print("Features (X) head:")
display(X.head())
print("Target (y) head:")
display(y.head())

# Create H2OFrame
df = h2o.H2OFrame(pd.concat([X, y], axis=1))

# Split into train/test
train, test = df.split_frame(ratios=[0.8], seed=42)

"""### 3.1 Run H2O AutoML for Regression"""

aml_reg = H2OAutoML(
    max_runtime_secs=300,
    max_models=20,
    seed=42,
    nfolds=5,
    project_name="california_regression"
)
aml_reg.train(x=X.columns.tolist(), y='target', training_frame=train)

# Show leaderboard
df_leader_reg = aml_reg.leaderboard.as_data_frame()
print(df_leader_reg.head())

# Evaluate on test
perf_reg = aml_reg.leader.model_performance(test)
print(f"H2O Regression R²: {perf_reg.r2():.4f}")
print(f"H2O Regression RMSE: {perf_reg.rmse():.4f}")

