def augment_minority_class(X, y, target_class, num_samples):
    # 1. Find indices for target_class
    idx = np.where(y == target_class)[0]
    X_minority = X[idx]
    y_minority = y[idx]

    # 2. ImageDataGenerator setup
    datagen = ImageDataGenerator(
        rotation_range=15,
        width_shift_range=0.1,
        height_shift_range=0.1,
        zoom_range=0.1,
        shear_range=0.1,
        fill_mode='nearest'
    )

    # 3. Generate new samples
    aug_X, aug_y = [], []
    generator = datagen.flow(X_minority, y_minority, batch_size=32, shuffle=True)

    while len(aug_X) < num_samples:
        X_batch, y_batch = next(generator)
        aug_X.append(X_batch)
        aug_y.append(y_batch)

    aug_X = np.concatenate(aug_X, axis=0)[:num_samples]
    aug_y = np.concatenate(aug_y, axis=0)[:num_samples]

    # 4. Combine with original data
    X_balanced = np.concatenate([X, aug_X], axis=0)
    y_balanced = np.concatenate([y, aug_y], axis=0)

    return X_balanced, y_balanced

