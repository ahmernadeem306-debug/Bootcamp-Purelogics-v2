def swap_words(text):
    words = text.split()
    if len(words) < 2:
        return text
    idx1, idx2 = random.sample(range(len(words)), 2)
    words[idx1], words[idx2] = words[idx2], words[idx1]
    return ' '.join(words)

def delete_random_word(text):
    words = text.split()
    if len(words) < 2:
        return text
    idx = random.randint(0, len(words)-1)
    words.pop(idx)
    return ' '.join(words)

def insert_random_word(text):
    words = text.split()
    vocab = ["data", "model", "AI", "feature", "result", "new", "very", "good"] # small vocab
    idx = random.randint(0, len(words))
    random_word = random.choice(vocab)
    words.insert(idx, random_word)
    return ' '.join(words)

